// Regenerate the bundled mana symbol artwork (lib/mana/symbols.generated.ts)
// from Scryfall's symbology endpoint.
//
// The symbols are inlined rather than fetched at runtime: a card list renders
// several per row, so remote requests would be both slow and offline-fragile.
// The full set is ~85 symbols / ~180KB of SVG markup.
//
// Run after a new Magic set introduces a symbol we don't have:
//   npm run gen:mana
import { mkdir, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

const SYMBOLOGY_URL = "https://api.scryfall.com/symbology";
const OUTPUT = fileURLToPath(
  new URL("../lib/mana/symbols.generated.ts", import.meta.url),
);
const USER_AGENT = "IWantMyMTG/1.0 (i-want-my-mtg-mobile)";

const BANNER = `// This file was auto-generated by scripts/gen-mana-symbols.mjs from
// ${SYMBOLOGY_URL}. Do not make direct changes to the file.
//
// Keys are the symbol code without braces, uppercased ("R", "W/U", "2/G").

export const MANA_SYMBOL_SVGS: Record<string, string> = {
`;

async function get(url) {
  const res = await fetch(url, { headers: { "User-Agent": USER_AGENT } });
  if (!res.ok) throw new Error(`${res.status} ${res.statusText} for ${url}`);
  return res;
}

const { data } = await (await get(SYMBOLOGY_URL)).json();

// Scryfall's response order is not part of its contract, so sort by key -
// regenerating then only diffs the symbols that actually changed. Compare by
// code unit rather than localeCompare, which would vary by machine locale.
const symbols = data
  .map((s) => ({ key: s.symbol.slice(1, -1).toUpperCase(), uri: s.svg_uri }))
  .sort((a, b) => (a.key < b.key ? -1 : a.key > b.key ? 1 : 0));

const entries = [];
for (const { key, uri } of symbols) {
  const svg = (await (await get(uri)).text()).trim();
  entries.push(`  ${JSON.stringify(key)}: ${JSON.stringify(svg)},`);
}

await mkdir(fileURLToPath(new URL("../lib/mana", import.meta.url)), {
  recursive: true,
});
await writeFile(OUTPUT, BANNER + entries.join("\n") + "\n};\n");
console.log(`Generated ${OUTPUT} with ${entries.length} symbols`);
